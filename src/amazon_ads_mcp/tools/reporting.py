"""Asynchronous performance reports (reporting v3).

A report is requested, generated by Amazon in the background (usually a few
minutes), then downloaded as gzipped JSON. Rows are parsed in memory and
returned; they are never written to disk or the audit log.
"""

from __future__ import annotations

import asyncio
import re
import time
from typing import Any

from mcp.server.mcpserver import Context

from ..client import AmazonAdsAPIError, AmazonAdsClient
from ._common import path_id
from ._progress import report, run_blocking

CREATE_MEDIA = "application/vnd.createasyncreportrequest.v3+json"
GET_MEDIA = "application/vnd.getasyncreportresponse.v3+json"
AD_PRODUCTS = {
    "SPONSORED_PRODUCTS",
    "SPONSORED_BRANDS",
    "SPONSORED_DISPLAY",
    "SPONSORED_TELEVISION",
    "DEMAND_SIDE_PLATFORM",
    "ALL",
}
_UUID = re.compile(r"[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}")

# Common starting points; any report type the API supports can be requested.
EXAMPLES = """\
Common report types (reportTypeId -> typical groupBy):
  spCampaigns -> ["campaign"] or ["campaign", "adGroup"]
  spTargeting -> ["targeting"]          (keyword and product target performance)
  spSearchTerm -> ["searchTerm"]        (customer search terms)
  spAdvertisedProduct -> ["advertiser"] (performance by advertised SKU/ASIN)
  sbCampaigns -> ["campaign"]; sbTargeting -> ["targeting"]; sbSearchTerm -> ["searchTerm"]
  sdCampaigns -> ["campaign"]; sdTargeting -> ["targeting"]; sdAdvertisedProduct -> ["advertiser"]
Typical SP columns: date, campaignName, campaignId, impressions, clicks, cost,
  purchases7d, sales7d, unitsSoldClicks7d, clickThroughRate, costPerClick.
Valid columns and filters differ by report type and groupBy; if a request is
rejected the error lists what's allowed. Data covers roughly the last 95 days."""


def _body(
    report_type_id: str,
    ad_product: str,
    start_date: str,
    end_date: str,
    columns: list[str],
    group_by: list[str],
    time_unit: str,
    filters: list[dict[str, Any]] | None,
    name: str | None,
) -> dict[str, Any]:
    ad_product = ad_product.upper()
    if ad_product not in AD_PRODUCTS:
        raise ValueError(f"ad_product must be one of {', '.join(sorted(AD_PRODUCTS))}.")
    time_unit = time_unit.upper()
    if time_unit not in {"DAILY", "SUMMARY"}:
        raise ValueError("time_unit must be DAILY or SUMMARY.")
    if not columns:
        raise ValueError("Pass at least one column.")
    if not group_by:
        raise ValueError("Pass at least one group_by value.")
    config: dict[str, Any] = {
        "adProduct": ad_product,
        "reportTypeId": report_type_id,
        "columns": columns,
        "groupBy": group_by,
        "timeUnit": time_unit,
        "format": "GZIP_JSON",
    }
    if filters:
        config["filters"] = filters
    body: dict[str, Any] = {
        "startDate": start_date,
        "endDate": end_date,
        "configuration": config,
    }
    if name:
        body["name"] = name
    return body


def register(mcp, client: AmazonAdsClient) -> None:
    def create(body: dict[str, Any], profile_id: str | None) -> dict[str, Any]:
        try:
            return client.request(
                "POST",
                "/reporting/reports",
                json_body=body,
                profile_id=profile_id,
                content_type=CREATE_MEDIA,
                accept="application/vnd.createasyncreportresponse.v3+json",
                read_only=True,
            )
        except AmazonAdsAPIError as e:
            # 425: an identical report is already being generated; reuse it.
            match = _UUID.search(str(e.body)) if e.status == 425 else None
            if match:
                return {
                    "reportId": match.group(0),
                    "status": "PENDING",
                    "duplicate_of_existing": True,
                }
            raise

    def get(report_id: str, profile_id: str | None) -> dict[str, Any]:
        return client.request(
            "GET",
            f"/reporting/reports/{path_id(report_id, 'report_id')}",
            profile_id=profile_id,
            accept=GET_MEDIA,
        )

    def rows_payload(status: dict[str, Any], max_rows: int) -> dict[str, Any]:
        rows = client.download_report(status["url"])
        return {
            "report_id": status.get("reportId"),
            "status": status.get("status"),
            "row_count": len(rows),
            "rows": rows[: max(0, max_rows)],
            "truncated": len(rows) > max_rows,
        }

    @mcp.tool(
        description=(
            "Request a performance report. It is generated in the background: poll "
            "amazon_ads_get_report, then call amazon_ads_download_report (or use "
            "amazon_ads_run_report to do all three).\n\n"
            "Dates are YYYY-MM-DD. time_unit DAILY adds a row per day (include the 'date' "
            "column); SUMMARY totals the range. filters, e.g. "
            '[{"field": "campaignStatus", "values": ["ENABLED"]}].\n\n' + EXAMPLES
        )
    )
    def amazon_ads_create_report(
        report_type_id: str,
        start_date: str,
        end_date: str,
        columns: list[str],
        group_by: list[str],
        ad_product: str = "SPONSORED_PRODUCTS",
        time_unit: str = "SUMMARY",
        filters: list[dict[str, Any]] | None = None,
        name: str | None = None,
        profile_id: str | None = None,
    ) -> dict[str, Any]:
        body = _body(
            report_type_id,
            ad_product,
            start_date,
            end_date,
            columns,
            group_by,
            time_unit,
            filters,
            name,
        )
        return create(body, profile_id)

    @mcp.tool()
    def amazon_ads_get_report(report_id: str, profile_id: str | None = None) -> dict[str, Any]:
        """Check a report's status: PENDING, PROCESSING, COMPLETED or FAILED.

        When COMPLETED, call amazon_ads_download_report to get the rows.
        """
        status = get(report_id, profile_id)
        status.pop("url", None)  # short-lived signed link; download_report fetches it
        return status

    @mcp.tool()
    def amazon_ads_download_report(
        report_id: str, max_rows: int = 1000, profile_id: str | None = None
    ) -> dict[str, Any]:
        """Download a COMPLETED report and return its rows (up to max_rows).

        Rows are held in memory only. row_count is the full count; truncated says
        whether rows were cut to max_rows.
        """
        status = get(report_id, profile_id)
        if status.get("status") != "COMPLETED" or not status.get("url"):
            return {
                "report_id": report_id,
                "status": status.get("status"),
                "failure_reason": status.get("failureReason"),
                "message": "Report isn't ready; check again with amazon_ads_get_report.",
            }
        return rows_payload(status, max_rows)

    @mcp.tool(
        description=(
            "Request a report, wait for it with progress updates, and return its rows. "
            "Same arguments as amazon_ads_create_report, plus timeout_seconds (default "
            "600), poll_seconds (default 15) and max_rows (default 1000). If it times out "
            "the report_id is returned so you can check later with amazon_ads_get_report.\n\n"
            + EXAMPLES
        )
    )
    async def amazon_ads_run_report(
        report_type_id: str,
        start_date: str,
        end_date: str,
        columns: list[str],
        group_by: list[str],
        ad_product: str = "SPONSORED_PRODUCTS",
        time_unit: str = "SUMMARY",
        filters: list[dict[str, Any]] | None = None,
        name: str | None = None,
        max_rows: int = 1000,
        timeout_seconds: float = 600,
        poll_seconds: float = 15,
        profile_id: str | None = None,
        ctx: Context | None = None,
    ) -> dict[str, Any]:
        body = _body(
            report_type_id,
            ad_product,
            start_date,
            end_date,
            columns,
            group_by,
            time_unit,
            filters,
            name,
        )
        created = await run_blocking(create, body, profile_id)
        report_id = created.get("reportId")
        if not report_id:
            raise RuntimeError(f"No reportId in the response: {created}")
        # Total time is unknown, so progress counts steps with no total.
        step = 1
        await report(ctx, step, None, f"Requested report {report_id}")
        deadline = time.monotonic() + timeout_seconds
        status: dict[str, Any] = created
        while True:
            status = await run_blocking(get, report_id, profile_id)
            state = status.get("status")
            step += 1
            if state == "COMPLETED" and status.get("url"):
                await report(ctx, step, None, "Report ready; downloading")
                payload = await run_blocking(rows_payload, status, max_rows)
                await report(ctx, step + 1, None, f"Downloaded {payload['row_count']} rows")
                return payload
            if state == "FAILED":
                return {
                    "report_id": report_id,
                    "status": state,
                    "failure_reason": status.get("failureReason"),
                }
            if time.monotonic() >= deadline:
                return {
                    "report_id": report_id,
                    "status": state,
                    "message": "Still generating. Check later with amazon_ads_get_report.",
                }
            await report(ctx, step, None, f"Report {state}; waiting")
            await asyncio.sleep(max(0.0, poll_seconds))
